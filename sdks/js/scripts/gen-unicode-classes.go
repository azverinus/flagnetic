// Generates src/evaluator/unicode-classes.ts: every name Go's regexp/syntax
// accepts in \p{name}, in its canonical form, mapped to the JavaScript
// property escape with the same code points. Regenerate after a Go upgrade:
//
//	pnpm gen:unicode
package main

import (
	"fmt"
	"regexp"
	"sort"
	"unicode"
)

// canonicalName is regexp/syntax's: separators dropped, the first letter
// upper-case, the rest lower-case.
func canonicalName(name string) string {
	var b []byte
	first := true
	for i := range len(name) {
		c := name[i]
		switch {
		case c == '_' || c == '-' || c == ' ':
			continue
		case first:
			if 'a' <= c && c <= 'z' {
				c -= 'a' - 'A'
			}
			first = false
		default:
			if 'A' <= c && c <= 'Z' {
				c += 'a' - 'A'
			}
		}
		b = append(b, c)
	}
	return string(b)
}

func main() {
	names := map[string]string{}
	add := func(name, escape string) {
		c := canonicalName(name)
		if _, ok := names[c]; ok {
			return
		}
		// Only what Go's parser accepts: some script names are unreachable.
		if _, err := regexp.Compile(`\p{` + c + `}`); err != nil {
			return
		}
		names[c] = escape
	}
	for _, k := range sortedKeys(unicode.Categories) {
		add(k, `\p{gc=`+k+`}`)
	}
	for _, k := range sortedKeys(unicode.Scripts) {
		add(k, `\p{sc=`+k+`}`)
	}
	aliases := make([]string, 0, len(unicode.CategoryAliases))
	for k := range unicode.CategoryAliases {
		aliases = append(aliases, k)
	}
	sort.Strings(aliases)
	for _, k := range aliases {
		add(k, `\p{gc=`+unicode.CategoryAliases[k]+`}`)
	}

	keys := make([]string, 0, len(names))
	for k := range names {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	fmt.Printf("// Code generated by scripts/gen-unicode-classes.go from Go's unicode %s; DO NOT EDIT.\n\n", unicode.Version)
	fmt.Println("// The canonical names Go's regexp/syntax accepts in \\p{name}, besides Any,")
	fmt.Println("// Assigned and Ascii, and the JavaScript property escape for each.")
	fmt.Println("export const unicodeClasses: ReadonlyMap<string, string> = new Map([")
	for _, k := range keys {
		fmt.Printf("  [%q, %q],\n", k, names[k])
	}
	fmt.Println("]);")
}

func sortedKeys(m map[string]*unicode.RangeTable) []string {
	keys := make([]string, 0, len(m))
	for k := range m {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	return keys
}
