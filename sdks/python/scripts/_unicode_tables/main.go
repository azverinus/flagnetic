// Command _unicode_tables writes src/flagnetic/_eval/_re2/unicode_tables.py
// from the Go standard library's unicode package, which the reference
// evaluator's regexp package uses: the simple case folding that (?i) applies,
// and the categories and scripts \p accepts with the characters that fold into
// each. Python ships no script data and its Unicode version moves with the
// interpreter, so the engine takes Go's tables and matches the same characters
// on every Python. The leading underscore keeps the command out of the root
// module's ./... pattern.
//
//	go run ./sdks/python/scripts/_unicode_tables > sdks/python/src/flagnetic/_eval/_re2/unicode_tables.py
package main

import (
	"fmt"
	"slices"
	"strings"
	"unicode"
)

func main() {
	var out strings.Builder
	out.WriteString("\"\"\"Unicode tables of Go's regexp, generated by scripts/_unicode_tables. Do not edit.\"\"\"\n\n")
	fmt.Fprintf(&out, "UNICODE_VERSION = %q\n\n", unicode.Version)

	var folds []string
	for r := rune(0); r <= unicode.MaxRune; r++ {
		if f := unicode.SimpleFold(r); f != r {
			folds = append(folds, fmt.Sprintf("%x-%x", r, f))
		}
	}
	out.WriteString("# SIMPLE_FOLD maps each code point to the next of its case folding orbit.\n")
	out.WriteString(constant("SIMPLE_FOLD", strings.Join(folds, " ")))

	out.WriteString("\n# CATEGORY_ALIASES are the long names of the categories, as Go spells them.\n")
	out.WriteString("CATEGORY_ALIASES = {\n")
	for _, name := range sortedKeys(unicode.CategoryAliases) {
		fmt.Fprintf(&out, "    %q: %q,\n", name, unicode.CategoryAliases[name])
	}
	out.WriteString("}\n")

	table(&out, "CATEGORIES", unicode.Categories)
	table(&out, "FOLD_CATEGORIES", unicode.FoldCategory)
	table(&out, "SCRIPTS", unicode.Scripts)
	table(&out, "FOLD_SCRIPTS", unicode.FoldScript)
	fmt.Print(out.String())
}

func sortedKeys[V any](m map[string]V) []string {
	keys := make([]string, 0, len(m))
	for k := range m {
		keys = append(keys, k)
	}
	slices.Sort(keys)
	return keys
}

// table writes one name to code point ranges dictionary, each range list as
// one hexadecimal string, "lo-hi lo-hi".
func table(out *strings.Builder, name string, tables map[string]*unicode.RangeTable) {
	fmt.Fprintf(out, "\n%s = {\n", name)
	for _, key := range sortedKeys(tables) {
		fmt.Fprintf(out, "    %q: (\n%s    ),\n", key, wrap(ranges(tables[key])))
	}
	out.WriteString("}\n")
}

// ranges lists the code points of t as maximal runs, expanding strides.
func ranges(t *unicode.RangeTable) string {
	var points []rune
	for _, r := range t.R16 {
		for c := rune(r.Lo); c <= rune(r.Hi); c += rune(r.Stride) {
			points = append(points, c)
		}
	}
	for _, r := range t.R32 {
		for c := rune(r.Lo); c <= rune(r.Hi); c += rune(r.Stride) {
			points = append(points, c)
		}
	}
	slices.Sort(points)
	var runs []string
	for i := 0; i < len(points); {
		j := i
		for j+1 < len(points) && points[j+1] == points[j]+1 {
			j++
		}
		runs = append(runs, fmt.Sprintf("%x-%x", points[i], points[j]))
		i = j + 1
	}
	return strings.Join(runs, " ")
}

func constant(name, value string) string {
	return name + " = (\n" + wrap(value) + ")\n"
}

// wrap splits a space separated string into adjacent Python string literals
// of at most 96 characters, each ending in a space but the last.
func wrap(value string) string {
	words := strings.Fields(value)
	var b strings.Builder
	var line strings.Builder
	flush := func(last bool) {
		text := line.String()
		if !last {
			text += " "
		}
		fmt.Fprintf(&b, "        %q\n", text)
		line.Reset()
	}
	for _, w := range words {
		if line.Len() > 0 && line.Len()+1+len(w) > 88 {
			flush(false)
		}
		if line.Len() > 0 {
			line.WriteByte(' ')
		}
		line.WriteString(w)
	}
	if line.Len() > 0 {
		flush(true)
	} else {
		b.WriteString("        \"\"\n")
	}
	return b.String()
}
