// Command _unicode_tables writes lib/flagnetic/eval/unicode_tables.rb from
// the Go standard library's unicode package, which the reference evaluator's
// regexp package uses: the simple case folding orbits (?i) folds with, and
// the category and script names \p accepts. The leading underscore keeps it
// out of the root module's ./... pattern.
//
//	go run ./sdks/ruby/script/_unicode_tables > sdks/ruby/lib/flagnetic/eval/unicode_tables.rb
package main

import (
	"fmt"
	"slices"
	"strings"
	"unicode"
)

func main() {
	seen := map[rune]bool{}
	var orbits []string
	for r := rune(0); r <= unicode.MaxRune; r++ {
		if seen[r] || unicode.SimpleFold(r) == r {
			continue
		}
		orbit := []string{fmt.Sprintf("%x", r)}
		seen[r] = true
		for f := unicode.SimpleFold(r); f != r; f = unicode.SimpleFold(f) {
			orbit = append(orbit, fmt.Sprintf("%x", f))
			seen[f] = true
		}
		orbits = append(orbits, strings.Join(orbit, " ")+",")
	}
	orbits[len(orbits)-1] = strings.TrimSuffix(orbits[len(orbits)-1], ",")
	var names []string
	for n := range unicode.Categories {
		names = append(names, n)
	}
	for n := range unicode.Scripts {
		names = append(names, n)
	}
	slices.Sort(names)

	fmt.Printf(`# frozen_string_literal: true

# Generated by script/_unicode_tables from Go's unicode package (Unicode %s).
# Do not edit.

module Flagnetic
  module Eval
    # UnicodeTables holds what the reference evaluator's regular expressions
    # take from Go's unicode package, so this evaluator folds case and accepts
    # \p names the same way whatever Unicode version the running Ruby ships.
    module UnicodeTables
      # ORBITS are the simple case folding orbits (?i) folds with.
      ORBITS = <<~ORBITS.split(",").map { |o| o.split.map(&:hex).freeze }.freeze
%s      ORBITS

      # PROPERTY_NAMES are the category and script names \p accepts besides Any.
      PROPERTY_NAMES = %%w[
%s      ].freeze
    end
  end
end
`, unicode.Version, wrap(orbits, ""), wrap(names, " "))
}

func wrap(words []string, sep string) string {
	var b, line strings.Builder
	for _, w := range words {
		if line.Len() > 0 && line.Len()+len(sep)+len(w) > 100 {
			b.WriteString("        " + line.String() + "\n")
			line.Reset()
		}
		if line.Len() > 0 {
			line.WriteString(sep)
		}
		line.WriteString(w)
	}
	if line.Len() > 0 {
		b.WriteString("        " + line.String() + "\n")
	}
	return b.String()
}
